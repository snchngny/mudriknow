const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const root = path.resolve(__dirname, '..');
const version = '1.19.3';
const platform = process.platform === 'win32' ? 'windows' : process.platform;
const name = process.platform === 'win32' ? 'opencode.exe' : 'opencode';
const packageName = `opencode-${platform}-${process.arch}`;
const base = path.join(root, '.local/opencode/node_modules', packageName);
const meta = JSON.parse(fs.readFileSync(path.join(base, 'package.json'), 'utf8'));
if (meta.version !== version) throw new Error(`Expected OpenCode ${version}`);
const source = path.join(base, 'bin', name);
const output = path.join(root, '.local/bundled-opencode');
fs.mkdirSync(output, { recursive: true });
fs.copyFileSync(source, path.join(output, name));
fs.chmodSync(path.join(output, name), 0o755);
fs.copyFileSync(path.join(root, 'THIRD_PARTY_NOTICES.txt'), path.join(output, 'THIRD_PARTY_NOTICES.txt'));
fs.writeFileSync(path.join(output, 'manifest.json'), JSON.stringify({ version, platform: process.platform, arch: process.arch, sha256: createHash('sha256').update(fs.readFileSync(source)).digest('hex') }, null, 2));
console.log(`Bundled OpenCode ${version} (${process.platform}/${process.arch})`);
